posts_by_id = {post['id']: post for post in posts}


def index(request):
    """Отображает главную страницу блога со списком постов в обратном порядке."""

    context = {'posts': posts[::-1]}
    return render(request, 'blog/index.html', context)


def post_detail(request, post_id):
    """Отображает страницу отдельного поста по его идентификатору.

    Args:
        request: HTTP-запрос.
        post_id: Идентификатор поста.

    Raises:
        Http404: Если пост с указанным id не найден.
    """

    post = posts_by_id.get(post_id)

    if post is None:
        raise Http404(f'Пост с id={post_id} не найден')

    return render(request, 'blog/detail.html', {'post': post})


def category_posts(request, category_slug):
    """Отображает посты, принадлежащие указанной категории.

    Args:
        request: HTTP-запрос.
        category_slug: Слаг категории для фильтрации постов.
    """

    category_posts = [p for p in posts if p['category'] == category_slug]
    context = {
        'category': category_slug,
        'posts': category_posts,
    }
    return render(request, 'blog/category.html', context)
